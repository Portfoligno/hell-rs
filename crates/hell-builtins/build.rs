fn emit_string_slice_field(generated: &mut String, field: &str, values: &[String]) {
    write!(generated, "{field}: &[").expect("write slice field");
    for value in values {
        write!(generated, "{value:?},").expect("write slice value");
    }
    generated.push_str("],");
}
